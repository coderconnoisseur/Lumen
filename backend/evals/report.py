"""Turn committed release results into markdown (SPEC-EVAL "Reporting"). Numbers are never typed by hand.

    python -m evals.report            # writes results/release-*.md and the README table

Reads the latest `results/release-<n>-<tier>-<split>.json` per tier and split. Every rate is shown with its
counts and 95% CI, and every column names its tier, release and the models that answered. The README table
lives between `<!-- eval:start -->` and `<!-- eval:end -->`; everything else in the README is left alone.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

EVALS_DIR = Path(__file__).resolve().parent
RESULTS_DIR = EVALS_DIR / "results"
README = EVALS_DIR.parents[1] / "README.md"
START, END = "<!-- eval:start -->", "<!-- eval:end -->"
_RELEASE = re.compile(r"release-(\d+)-([a-z]+)-(dev|test)\.json$")

# (label, suite, path into that suite's metrics, kind)
ROWS = (
    ("Text-to-SQL execution accuracy (gated)", "sql", ("execution_accuracy",), "rate"),
    ("Text-to-SQL strict accuracy (identical columns)", "sql", ("strict_execution_accuracy",), "rate"),
    ("SQL fallback rate (lower is better)", "sql", ("fallback_rate",), "rate"),
    ("Extraction field F1", "extraction", ("field_f1",), "number"),
    ("Extraction F1, clean scans", "extraction", ("f1_by_variant", "clean"), "number"),
    ("Extraction F1, degraded scans", "extraction", ("f1_by_variant", "degraded"), "number"),
    ("Invoices with every field right", "extraction", ("all_fields_correct",), "rate"),
    ("Tenant leaks (must be 0)", "safety", ("tenant_leaks",), "count"),
    ("Prompt injections followed (must be 0)", "safety", ("injections_followed",), "count"),
    ("SQL latency p50 / p95 (recorded)", "sql", ("ops", "latency_s_recorded"), "latency"),
    ("SQL cost per question (list-price equivalent)", "sql", ("ops", "cost_usd_per_question_list_price"), "usd"),
)


def latest_releases(results_dir: Path = RESULTS_DIR) -> dict[tuple[str, str], tuple[int, dict]]:
    """{(tier, split): (release number, report)} for the newest release of each."""
    found: dict[tuple[str, str], tuple[int, dict]] = {}
    for path in sorted(results_dir.glob("release-*.json")):
        match = _RELEASE.search(path.name)
        if not match:
            continue
        n, tier, split = int(match.group(1)), match.group(2), match.group(3)
        if (tier, split) not in found or n > found[(tier, split)][0]:
            found[(tier, split)] = (n, json.loads(path.read_text(encoding="utf-8")))
    return found


def _dig(metrics: dict, path: tuple):
    for key in path:
        if not isinstance(metrics, dict) or key not in metrics:
            return None
        metrics = metrics[key]
    return metrics


def cell(value, kind: str) -> str:
    if value is None:
        return "n/a"
    if kind == "rate":
        low, high = value["ci95"]
        return f"{value['passed']}/{value['total']} ({value['value']:.0%}, CI {low:.0%}-{high:.0%})"
    if kind == "number":
        return f"{value:.3f}"
    if kind == "count":
        return str(value)
    if kind == "latency":
        if value.get("p50") is None:
            return "n/a"
        return f"{value['p50']:.1f} s / {value['p95']:.1f} s"
    if kind == "usd":
        return f"${value:.5f}"
    raise ValueError(kind)


def _models(report: dict) -> str:
    models = set()
    for suite in report.get("suites", {}).values():
        models.update((_dig(suite.get("metrics", {}), ("ops", "models")) or {}).keys())
    return ", ".join(f"`{m}`" for m in sorted(models)) or "none recorded"


def table(releases: dict[tuple[str, str], tuple[int, dict]], split: str) -> str:
    """One markdown table for a split: a column per tier, then which models answered."""
    columns = sorted((tier, n, rep) for (tier, s), (n, rep) in releases.items() if s == split)
    if not columns:
        return f"_No {split}-split release results yet._\n"
    head = "| Metric | " + " | ".join(f"{tier} (release {n})" for tier, n, _ in columns) + " |"
    lines = [head, "|---|" + "---|" * len(columns)]
    for label, suite, path, kind in ROWS:
        values = []
        for _, _, rep in columns:
            metrics = (rep.get("suites", {}).get(suite) or {}).get("metrics")
            values.append(cell(_dig(metrics, path) if metrics else None, kind))
        if any(v != "n/a" for v in values):
            lines.append(f"| {label} | " + " | ".join(values) + " |")
    lines.append("")
    lines += [f"- **{tier}** models: {_models(rep)}" for tier, _, rep in columns]
    return "\n".join(lines) + "\n"


def readme_section(releases) -> str:
    return (
        "Generated by `python -m evals.report` from `backend/evals/results/release-*.json`; "
        "don't edit by hand. Rates show counts and 95% Wilson intervals.\n\n"
        "**Dev split**\n\n" + table(releases, "dev") + "\n**Test split** (release runs only)\n\n"
        + table(releases, "test")
    )


def update_readme(text: str, section: str) -> str:
    if START not in text or END not in text:
        raise ValueError(f"README needs {START} and {END} markers")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    return f"{before}{START}\n{section}{END}{after}"


def release_markdown(tier: str, split: str, n: int, report: dict) -> str:
    """Everything in one release file, readable: headline table plus each suite's full metrics."""
    out = [f"# Release {n}: {tier}, {split} split", "", table({(tier, split): (n, report)}, split)]
    for name, suite in sorted(report.get("suites", {}).items()):
        out += [f"## {name}", "", "```json", json.dumps(suite.get("metrics", {}), indent=2, sort_keys=True),
                "```", ""]
        if suite.get("hard_gate_failures"):
            out += ["Hard-gate failures:", *[f"- {f}" for f in suite["hard_gate_failures"]], ""]
    return "\n".join(out)


def main(argv=None, *, results_dir: Path = RESULTS_DIR, readme: Path = README) -> int:
    argparse.ArgumentParser(prog="python -m evals.report", description=__doc__.split("\n\n")[0]).parse_args(argv)
    releases = latest_releases(results_dir)
    for (tier, split), (n, report) in releases.items():
        (results_dir / f"release-{n}-{tier}-{split}.md").write_text(
            release_markdown(tier, split, n, report), encoding="utf-8", newline="\n")
    readme.write_text(update_readme(readme.read_text(encoding="utf-8"), readme_section(releases)),
                      encoding="utf-8", newline="\n")
    print(f"{len(releases)} release result(s) -> {readme.name} and results/*.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
